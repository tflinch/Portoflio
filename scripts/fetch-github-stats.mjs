#!/usr/bin/env node
/**
 * Fetches the GitHub contribution total at build time and writes it to
 * src/generated/github-stats.ts.
 *
 * GITHUB_TOKEN is read from the build environment and is deliberately NOT
 * VITE_-prefixed: Vite inlines anything with that prefix into the client bundle.
 *
 * This never fails the build. If the token is missing or GitHub is unreachable,
 * the previously committed value stays in place.
 */
import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/generated/github-stats.ts'
);
const LOGIN = 'tflinch';
const QUERY = `query($login: String!) {
  user(login: $login) {
    contributionsCollection {
      contributionCalendar { totalContributions }
    }
  }
}`;

const token = process.env.GITHUB_TOKEN;
if (!token) {
  console.warn('[github-stats] GITHUB_TOKEN not set - keeping committed value.');
  process.exit(0);
}

try {
  const response = await fetch('https://api.github.com/graphql', {
    method: 'POST',
    headers: {
      authorization: `bearer ${token}`,
      'content-type': 'application/json',
      'user-agent': 'portfolio-build',
    },
    body: JSON.stringify({ query: QUERY, variables: { login: LOGIN } }),
    signal: AbortSignal.timeout(10_000),
  });

  if (!response.ok) throw new Error(`GitHub responded ${response.status}`);

  const result = await response.json();
  if (result.errors) throw new Error(result.errors.map((e) => e.message).join('; '));

  const total =
    result.data.user.contributionsCollection.contributionCalendar.totalContributions;

  await writeFile(
    OUT,
    [
      '// Generated by scripts/fetch-github-stats.mjs. Committed so the build never',
      '// depends on GitHub being reachable. Overwritten on each successful build.',
      `export const totalContributions = ${total};`,
      `export const fetchedAt = '${new Date().toISOString()}';`,
      '',
    ].join('\n')
  );
  console.log(`[github-stats] ${total} contributions written.`);
} catch (error) {
  console.warn(`[github-stats] fetch failed (${error.message}) - keeping committed value.`);
}
